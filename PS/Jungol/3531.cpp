// 1 -> 4 -> 9 -> 16
// (2, 0), (0, 2), (-2, 0), (0, -2),
// (1, 1), (-1, 1), (-1, -1), (1, -1),
// (3, 0), (0, 3), (-3, 0), (0, -3),
// (1, 2), (1, -2), (2, 1), (2, -1)

// 1 1 2 3 5 8 13 ...
// f(n) = f(n-1) + f(n-2)
// f(0) -> 1, f(1) -> 4, f(2) -> 9

